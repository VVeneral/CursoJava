package PraticasCurso;

public class operadoresAtribuicaoExercicio {
    public static void main(String [] args) {
        int numero = 5;

        numero += 3;
        System.out.println("R: " + numero);

        numero -= 2;
        System.out.println("R: " + numero);

        numero *= 4;
        System.out.println("R: " + numero);

        numero /= 4;
        System.out.println("R: " + numero);
    }
}
