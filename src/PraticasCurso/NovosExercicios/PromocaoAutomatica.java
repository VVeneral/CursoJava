package PraticasCurso.NovosExercicios;

public class PromocaoAutomatica {
    public static void main (String[] args) {

        byte a = 10;
        char b = 'A';
        int c = 15;
        long d = 20L;
        float e = 2.5f;
        double f = 3.5;

        int result1 = a + c;
        long result2 = c + d;
        float result3 = d + e;
        double result4 = e * f;

        System.out.println("resultado char: " + b);
        System.out.println("Resultado: " + result1);
        System.out.println("Resultado: " + result2);
        System.out.println("Resultado: " + result3);
        System.out.println("Resultado: " + result4);
    }
}
